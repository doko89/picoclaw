// ProcessPlanningAnswer records an answer to a planning question.
func ProcessPlanningAnswer(ctx context.Context, db *DB, taskID, questionID, answer string) error {
	_, err := db.ExecContext(ctx,
		"UPDATE planning_questions SET answer = ?, answered_at = datetime('now') WHERE id = ? AND task_id = ?",
		answer, questionID, taskID,
	)
	return err
}

// FinalizePlanningSpec creates a locked planning spec from answered questions.
func FinalizePlanningSpec(ctx context.Context, db *DB, taskID string) (string, error) {
	// Check if spec already exists
	var count int
	err := db.QueryRowContext(ctx,
		"SELECT COUNT(*) FROM planning_specs WHERE task_id = ?", taskID,
	).Scan(&count)
	if err != nil {
		return "", fmt.Errorf("check spec: %w", err)
	}
	if count > 0 {
		return "", fmt.Errorf("spec already locked")
	}

	// Get all answered questions
	rows, err := db.QueryContext(ctx,
		"SELECT category, question, answer FROM planning_questions WHERE task_id = ? AND answer IS NOT NULL ORDER BY sort_order",
		taskID,
	)
	if err != nil {
		return "", fmt.Errorf("get questions: %w", err)
	}
	defer rows.Close()

	var questions []planningQuestionRow
	for rows.Next() {
		var q planningQuestionRow
		if err := rows.Scan(&q.Category, &q.Question, &q.Answer); err != nil {
			continue
		}
		questions = append(questions, q)
	}

	// Get task info
	var title, description string
	db.QueryRowContext(ctx,
		"SELECT title, COALESCE(description, '') FROM tasks WHERE id = ?", taskID,
	).Scan(&title, &description)

	// Generate spec markdown
	specMarkdown := generateSpecMarkdown(title, description, questions)

	// Insert spec record
	specID := uuid.New().String()
	_, err = db.ExecContext(ctx,
		"INSERT INTO planning_specs (id, task_id, spec_markdown, locked_at) VALUES (?, ?, ?, datetime('now'))",
		specID, taskID, specMarkdown,
	)
	if err != nil {
		return "", fmt.Errorf("insert spec: %w", err)
	}

	// Update task status to inbox
	_, err = db.ExecContext(ctx,
		"UPDATE tasks SET description = ?, status = 'inbox', updated_at = datetime('now') WHERE id = ?",
		specMarkdown, taskID,
	)
	if err != nil {
		return "", fmt.Errorf("update task: %w", err)
	}

	return specID, nil
}

func generateSpecMarkdown(title, description string, questions []planningQuestionRow) string {
	var b strings.Builder

	b.WriteString("# ")
	b.WriteString(title)
	b.WriteString("\n\n**Status:** SPEC LOCKED ✅\n\n")

	if description != "" {
		b.WriteString("## Original Request\n")
		b.WriteString(description)
		b.WriteString("\n\n")
	}

	// Group by category
	catLabels := map[string]string{
		"goal":        "🎯 Goal & Success Criteria",
		"audience":    "👥 Target Audience",
		"scope":       "📋 Scope",
		"design":      "🎨 Design & Visual",
		"content":     "📝 Content",
		"technical":   "⚙️ Technical Requirements",
		"timeline":    "📅 Timeline",
		"constraints": "⚠️ Constraints",
	}

	catOrder := []string{"goal", "audience", "scope", "design", "content", "technical", "timeline", "constraints"}
	groups := map[string][]struct {
		Question string
		Answer   string
	}{}
	var seenCats []string

	for _, q := range questions {
		if _, ok := groups[q.Category]; !ok {
			seenCats = append(seenCats, q.Category)
		}
		groups[q.Category] = append(groups[q.Category], struct {
			Question string
			Answer   string
		}{q.Question, q.Answer})
	}

	// Merge seenCats into catOrder, preserving order
	allCats := catOrder
	for _, c := range seenCats {
		found := false
		for _, existing := range allCats {
			if existing == c {
				found = true
				break
			}
		}
		if !found {
			allCats = append(allCats, c)
		}
	}

	for _, cat := range allCats {
		qs, ok := groups[cat]
		if !ok || len(qs) == 0 {
			continue
		}
		label := cat
		if l, ok := catLabels[cat]; ok {
			label = l
		}
		b.WriteString("## ")
		b.WriteString(label)
		b.WriteString("\n\n")

		for _, q := range qs {
			b.WriteString("**")
			b.WriteString(q.Question)
			b.WriteString("**\n> ")
			b.WriteString(q.Answer)
			b.WriteString("\n\n")
		}
	}

	b.WriteString("---\n*Spec locked*\n")
	return b.String()
}